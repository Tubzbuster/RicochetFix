#!/usr/bin/env python3
"""Generate the proxy export stubs for RicochetFix.

RicochetFix can be installed as either winmm.dll or ddraw.dll, so it exports
every function of both. Each export is a one-instruction stub that jumps
through g_proxyProcs[], which is filled from the real system DLL that matches
the name the DLL was installed under (see src/proxy.c).

Run from the repository root:  python3 tools/gen_proxy.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")


def read_names(fname):
    with open(os.path.join(SRC, fname)) as f:
        return [n.strip() for n in f if n.strip()]


def main():
    sets = [("winmm", read_names("winmm_exports.txt")),
            ("ddraw", read_names("ddraw_exports.txt"))]
    entries = []  # (dll, name)
    seen = set()
    for dll, names in sets:
        for n in names:
            if n in seen:
                raise SystemExit("duplicate export: " + n)
            seen.add(n)
            entries.append((dll, n))

    hdr = ["/* Generated by tools/gen_proxy.py - do not edit. */",
           "#pragma once",
           "#define PROXY_COUNT %d" % len(entries),
           "typedef struct { const char *dll; const char *name; } ProxyExport;",
           "static const ProxyExport g_proxyExports[PROXY_COUNT] = {"]
    hdr += ['    {"%s", "%s"},' % e for e in entries]
    hdr += ["};", ""]
    with open(os.path.join(SRC, "proxy_names.h"), "w", newline="\n") as f:
        f.write("\n".join(hdr))

    asm = ["/* Generated by tools/gen_proxy.py - do not edit. */",
           "    .text"]
    for i, (_, n) in enumerate(entries):
        asm += ["    .globl _stub_%s" % n,
                "_stub_%s:" % n,
                "    jmp *_g_proxyProcs+%d" % (i * 4)]
    asm.append("")
    with open(os.path.join(SRC, "proxy_stubs.S"), "w", newline="\n") as f:
        f.write("\n".join(asm))

    df = ["; Generated by tools/gen_proxy.py - do not edit.", "EXPORTS"]
    df += ["    %s=stub_%s" % (n, n) for _, n in entries]
    df.append("")
    with open(os.path.join(SRC, "proxy.def"), "w", newline="\n") as f:
        f.write("\n".join(df))


if __name__ == "__main__":
    main()
